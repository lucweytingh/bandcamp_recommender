#!/usr/bin/env python3
"""Run the diversity strategy side-by-side and emit a markdown results report.

    uv run python scripts/run_diversity_eval.py > docs/diversity-eval-results.md

Framing (constrained optimization — matches the user's ask "intensity needs to
be similar… but I want a diverse range"):

  * CONSTRAINTS (hard): keep the seed's vibe (intensity band) and stay in its
    realm (related to the seed). These are enforced by the vibe gate, not traded
    against diversity. Reported as vibe_pass_rate + dispersion-vs-band.
  * OBJECTIVE (maximize): style diversity within the feasible set. Reported with
    independent measures so the verdict doesn't rest on any single (possibly
    self-referential) number:
      - div↑   continuous mean-pairwise style distance + categorical bonus
               (close to what mmr/maxmin optimize — labelled as such)
      - gcov↑  distinct GENRES per slice (no strategy maximizes a distinct count)
      - acov↑  distinct ARTISTS per slice (independent)
  * Q is the composite heuristic; it is dominated by the diversity term, so it is
    reported as context, NOT the sole arbiter (see the circularity check, §5).

Pure synthetic + seeded — fully reproducible.
"""
import random
import sys
from dataclasses import replace

sys.path.insert(0, ".")

from bandcamp_recommender.recommendations.diversity import GateConfig, ScoreWeights, select_mmr, vibe_gate, \
    set_diversity, intensity_dispersion, realm_relevance, vibe_diversity_score, \
    NEG_INF
from bandcamp_recommender.eval.diversity_eval import (
    RegimeConfig, run_regime, evaluate, default_regimes, VARIANTS,
    make_genres, make_seed, make_pool,
)

# 150 seeds is statistically ample here — the strategy effects are large and the
# fairness audit confirmed they're robust well beyond sampling noise. Kept modest
# so the multi-sweep report (≈50 oracle-bearing runs) regenerates in minutes.
N_SEEDS = 150
BASE_SEED = 20260616
COLS = ["vibe_pass_rate", "fill_rate", "mean_diversity", "mean_genre_coverage",
        "mean_artist_coverage", "mean_dispersion", "mean_relevance",
        "mean_Q_feasible", "mean_oracle_gap"]
SHORT = {"vibe_pass_rate": "vibe✓", "fill_rate": "fill", "mean_diversity": "div↑",
         "mean_genre_coverage": "gcov↑", "mean_artist_coverage": "acov↑",
         "mean_dispersion": "disp", "mean_relevance": "rel",
         "mean_Q_feasible": "Q", "mean_oracle_gap": "gap↓"}


def table(res):
    head = "| variant | " + " | ".join(SHORT[c] for c in COLS) + " |"
    sep = "|" + "---|" * (len(COLS) + 1)
    rows = [head, sep]
    for v in VARIANTS:
        m = res[v]
        cells = " | ".join(f"{m[c]:.3f}" for c in COLS)
        rows.append(f"| {v} | {cells} |")
    return "\n".join(rows)


def agg_across(results):
    return {v: {c: sum(results[r][v][c] for r in results) / len(results)
                for c in COLS} for v in VARIANTS}


def main():
    out = []
    p = out.append
    p("# Diversity strategy side-by-side — results\n")
    p(f"_Generated by `scripts/run_diversity_eval.py`. n_seeds={N_SEEDS} per "
      f"regime, base_seed={BASE_SEED}. Reproducible: rerun to reproduce exactly._\n")
    p("**Framing — constrained optimization.** The user's ask is *maximize "
      "diversity subject to the vibe staying similar and the music staying "
      "related to the seed*. So vibe (intensity band) and realm (seed-distance) "
      "are **constraints** enforced by the gate, not objectives to trade against "
      "diversity. Quality metrics below are computed over the **feasible** "
      "slices only (those that keep the vibe), so variants are compared on equal "
      "footing.\n")
    p("Legend — **vibe✓** fraction of slices that keep the seed's vibe "
      "(constraint satisfaction; higher better). **fill** fraction that filled "
      "k. Objective: **div↑** continuous style diversity (≈ what mmr/maxmin "
      "optimize), **gcov↑** distinct genres/slice, **acov↑** distinct "
      "artists/slice (gcov/acov are a *distinct categorical* measure — "
      "correlated with the continuous objective via the corpus's genre≈style "
      "structure, not identical to it; see §6). "
      "Constraint context: **disp** intensity dispersion within the slice (stays "
      "under the band by construction), **rel** mean seed-distance. **Q** the "
      "composite heuristic (context only — see §5). **gap↓** below the "
      "(approximate beam) oracle.\n")
    p("_Note: the headline comparison is **baseline_gated vs the strategies** — "
      "all four select from the identical gated pool and average over the same "
      "feasible slices. The ungated **baseline** row is context only; its quality "
      "cells average over just its in-vibe subset (survivorship-filtered), so they "
      "aren't directly comparable — read its **vibe✓** as the real story there._\n")

    p("## 1. Per-regime, all variants\n")
    results = evaluate(default_regimes(), n_seeds=N_SEEDS, base_seed=BASE_SEED)
    for name, res in results.items():
        p(f"### {name}\n")
        p(table(res) + "\n")
    p("### aggregate (mean across regimes)\n")
    agg = agg_across(results)
    p(table(agg) + "\n")

    p("## 2. MMR lambda sweep (diffuse_coupled_manygenre)\n")
    p("lambda=1 is the baseline (relevance only); lambda=0 is pure spread. Shows "
      "MMR's single knob spans the whole design space.\n")
    base_cfg = next(c for c in default_regimes() if c.name == "diffuse_coupled_manygenre")
    p("| lambda | div↑ | gcov↑ | disp | rel | Q |")
    p("|---|---|---|---|---|---|")
    for lam in (1.0, 0.75, 0.5, 0.25, 0.0):
        rng = random.Random(BASE_SEED + 100)
        divs, gcovs, disps, rels, qs = [], [], [], [], []
        for _ in range(N_SEEDS):
            genres = make_genres(base_cfg, rng)
            seed = make_seed(base_cfg, genres, rng)
            pool = make_pool(base_cfg, genres, seed, rng)
            gated = vibe_gate(pool, seed, base_cfg.gate)
            sel = select_mmr(gated, seed, base_cfg.k, lam=lam)
            if not sel:
                continue
            divs.append(set_diversity(sel, base_cfg.weights))
            gcovs.append(len({t.genre for t in sel}))
            disps.append(intensity_dispersion(sel))
            rels.append(realm_relevance(sel, seed))
            q = vibe_diversity_score(seed, sel, base_cfg.gate, base_cfg.weights)
            if q != NEG_INF:
                qs.append(q)
        mean = lambda xs: sum(xs) / len(xs) if xs else 0.0
        p(f"| {lam:.2f} | {mean(divs):.3f} | {mean(gcovs):.3f} | "
          f"{mean(disps):.3f} | {mean(rels):.3f} | {mean(qs):.3f} |")
    p("")

    p("## 3. Intensity-band (tau_int) sweep — the vibe constraint's tightness\n")
    p("Tighter band = tighter vibe but risks not filling k. "
      "(independent_intensity regime, mmr.)\n")
    ind_cfg = next(c for c in default_regimes() if c.name == "independent_intensity")
    p("| tau_int | vibe✓ | fill | disp | div↑ |")
    p("|---|---|---|---|---|")
    for tau in (0.10, 0.15, 0.20, 0.30):
        cfg = replace(ind_cfg, gate=GateConfig(tau_int=tau, realm_mult=1.5))
        res = run_regime(cfg, N_SEEDS, random.Random(BASE_SEED + 200))
        m = res["mmr"]
        p(f"| {tau:.2f} | {m['vibe_pass_rate']:.3f} | {m['fill_rate']:.3f} | "
          f"{m['mean_dispersion']:.3f} | {m['mean_diversity']:.3f} |")
    p("")

    p("## 4. k sweep (aggregate across regimes)\n")
    p("| k | strategy | div↑ | gcov↑ | disp | rel | gap↓ |")
    p("|---|---|---|---|---|---|---|")
    for k in (3, 4, 5):
        regimes_k = [replace(c, k=k) for c in default_regimes()]
        res = evaluate(regimes_k, n_seeds=N_SEEDS, base_seed=BASE_SEED + 300)
        for strat in ("mmr", "maxmin", "stratified"):
            row = {c: sum(res[r][strat][c] for r in res) / len(res) for c in
                   ("mean_diversity", "mean_genre_coverage", "mean_dispersion",
                    "mean_relevance", "mean_oracle_gap")}
            p(f"| {k} | {strat} | {row['mean_diversity']:.3f} | "
              f"{row['mean_genre_coverage']:.3f} | {row['mean_dispersion']:.3f} | "
              f"{row['mean_relevance']:.3f} | {row['mean_oracle_gap']:.3f} |")
    p("")

    p("## 5. Does the verdict survive a distinct (categorical) metric?\n")
    p("Q is ~dominated by its diversity term, which is close to what mmr/maxmin "
      "optimize, so ranking by Q alone would be partly self-referential. We "
      "therefore also rank by a *categorical* measure — distinct-genre coverage, "
      "which no strategy maximizes as a count. **Caveat (be honest):** this is a "
      "*distinct* function, not an *independent* one — in this corpus genre is the "
      "latent style cluster, so genre coverage is correlated with the continuous "
      "style objective (§6 quantifies how that correlation weakens as genre "
      "decouples from style). A set can still raise mean-pairwise style-distance "
      "without adding a genre (two far-apart members of two genres), so the two "
      "measures are not identical — but treat coverage as *correlated "
      "corroboration*, not a clean independent witness.\n")
    by_q = sorted(VARIANTS, key=lambda v: agg[v]["mean_Q_feasible"], reverse=True)
    by_g = sorted(VARIANTS, key=lambda v: agg[v]["mean_genre_coverage"], reverse=True)
    p(f"- Rank by **Q**: {' > '.join(by_q)}")
    p(f"- Rank by **genre-coverage**: {' > '.join(by_g)}")
    base_g = agg["baseline_gated"]["mean_genre_coverage"]
    p(f"- baseline_gated genre-coverage = {base_g:.3f}; "
      f"mmr={agg['mmr']['mean_genre_coverage']:.3f}, "
      f"maxmin={agg['maxmin']['mean_genre_coverage']:.3f}, "
      f"stratified={agg['stratified']['mean_genre_coverage']:.3f} — "
      "all above the gated top-k baseline (in the realistic genre≈style regime).\n")
    p("Additionally, with the categorical bonus removed (w_cat=0) so diversity is "
      "*pure* continuous style-distance, the ordering of the diversifiers over "
      "the baseline is unchanged (raw style spread, aggregate):\n")
    w0 = ScoreWeights(w_cat=0.0)
    regimes_w0 = [replace(c, weights=w0) for c in default_regimes()]
    res0 = evaluate(regimes_w0, n_seeds=N_SEEDS, base_seed=BASE_SEED + 400)
    agg0 = {v: sum(res0[r][v]["mean_diversity"] for r in res0) / len(res0)
            for v in VARIANTS}
    p("| variant | div↑ (w_cat=0) |")
    p("|---|---|")
    for v in VARIANTS:
        p(f"| {v} | {agg0[v]:.3f} |")
    p("")

    p("## 6. How independent is genre coverage? (genre↔style coupling)\n")
    p("If genre encodes style (a coherent collection), the categorical coverage "
      "metric corroborates the continuous one. As the within-genre jitter "
      "(style_std) grows, genre stops predicting style, and the coverage "
      "corroboration for the *style*-optimizers (mmr/maxmin) should fade — while "
      "the continuous diversity win persists, and stratified (which targets the "
      "genre count itself) keeps its coverage edge. Gaps are vs baseline_gated on "
      "the diffuse_coupled_manygenre regime.\n")
    p("| style_std | mmr Δgcov | maxmin Δgcov | stratified Δgcov | mmr Δdiv | maxmin Δdiv |")
    p("|---|---|---|---|---|---|")
    cpl_base = next(c for c in default_regimes() if c.name == "diffuse_coupled_manygenre")
    for sstd in (0.12, 0.25, 0.5, 1.0):
        cfg = replace(cpl_base, style_std=sstd)
        rr = run_regime(cfg, N_SEEDS, random.Random(BASE_SEED + 600))
        bg_g = rr["baseline_gated"]["mean_genre_coverage"]
        bg_d = rr["baseline_gated"]["mean_diversity"]
        dg = lambda s: rr[s]["mean_genre_coverage"] - bg_g
        dd = lambda s: rr[s]["mean_diversity"] - bg_d
        p(f"| {sstd:.2f} | {dg('mmr'):+.3f} | {dg('maxmin'):+.3f} | "
          f"{dg('stratified'):+.3f} | {dd('mmr'):+.3f} | {dd('maxmin'):+.3f} |")
    p("")
    p("Reading: mmr/maxmin's **Δgcov shrinks toward 0** as style_std rises (their "
      "coverage gain was genre-mediated), but their **Δdiv stays clearly "
      "positive** (the continuous spread win is real and regime-robust), and "
      "stratified's Δgcov stays largest (its win is intrinsic to its objective). "
      "So the honest, regime-independent claim is the *continuous* diversity win; "
      "coverage corroborates it only where genre tracks style.\n")

    p("## 7. Sensitivity to the relevance weight (w_rel)\n")
    p("Q trades diversity against seed-distance via w_rel. A skeptic notes that "
      "at large w_rel the baseline wins Q (it stays closest to the seed). True — "
      "but that just means *Q is not the arbiter*. The production decision rests "
      "on the constraints (vibe kept — same for all gated variants) plus the "
      "**w_rel-independent** objective the user actually asked for (a more varied "
      "set). Below: as w_rel varies, the Q-ranking shifts, yet the strategies "
      "beat the gated baseline on genre coverage (which has no w_rel in it) at "
      "every setting.\n")
    p("| w_rel | best-by-Q | baseline_gated gcov | mmr gcov | maxmin gcov | "
      "strategies > baseline on gcov? |")
    p("|---|---|---|---|---|---|")
    for wr in (0.0, 0.5, 2.0, 8.0):
        wcfg = ScoreWeights(w_rel=wr)
        regimes_wr = [replace(c, weights=wcfg) for c in default_regimes()]
        rr = evaluate(regimes_wr, n_seeds=N_SEEDS, base_seed=BASE_SEED + 500)
        ragg = {v: {m: sum(rr[r][v][m] for r in rr) / len(rr)
                    for m in ("mean_Q_feasible", "mean_genre_coverage")}
                for v in VARIANTS}
        compet = [v for v in VARIANTS if v != "oracle"]
        best = max(compet, key=lambda v: ragg[v]["mean_Q_feasible"])
        bg = ragg["baseline_gated"]["mean_genre_coverage"]
        beat = all(ragg[s]["mean_genre_coverage"] >= bg - 1e-9
                   for s in ("mmr", "maxmin", "stratified"))
        p(f"| {wr:.1f} | {best} | {bg:.3f} | {ragg['mmr']['mean_genre_coverage']:.3f} | "
          f"{ragg['maxmin']['mean_genre_coverage']:.3f} | {'yes' if beat else 'NO'} |")
    p("")

    p("## 8. Conclusion\n")
    a = agg
    p(f"- **The gate is what keeps the vibe.** Ungated baseline keeps vibe "
      f"{a['baseline']['vibe_pass_rate']*100:.0f}% of the time; every gated "
      f"variant is ~100%. The intensity-similarity requirement is met by the "
      f"hard gate, independent of which strategy runs.")
    p(f"- **All three strategies increase the continuous style diversity they "
      f"target over the gated top-k baseline** (div {a['baseline_gated']['mean_diversity']:.2f} "
      f"→ mmr {a['mmr']['mean_diversity']:.2f} / maxmin {a['maxmin']['mean_diversity']:.2f} / "
      f"stratified {a['stratified']['mean_diversity']:.2f}) — the robust, "
      f"regime-independent result. Distinct-genre coverage corroborates it in the "
      f"realistic genre≈style regime ({a['baseline_gated']['mean_genre_coverage']:.2f} "
      f"→ {a['mmr']['mean_genre_coverage']:.2f} / {a['maxmin']['mean_genre_coverage']:.2f} / "
      f"{a['stratified']['mean_genre_coverage']:.2f}), but that's *correlated* "
      f"corroboration, not independent (§5–§6): as genre decouples from style the "
      f"coverage gain for mmr/maxmin fades while their continuous win holds.")
    p(f"- **Trade-off:** maxmin maximizes raw spread (div {a['maxmin']['mean_diversity']:.2f}) "
      f"but drifts furthest from the seed (rel {a['maxmin']['mean_relevance']:.2f}) "
      f"and runs slightly looser on vibe (disp {a['maxmin']['mean_dispersion']:.3f}). "
      f"mmr gives nearly as much diversity (div {a['mmr']['mean_diversity']:.2f}) "
      f"while staying most anchored (rel {a['mmr']['mean_relevance']:.2f}) and "
      f"tightest on vibe (disp {a['mmr']['mean_dispersion']:.3f}). stratified "
      f"maximizes genre/artist coverage but depends on genre labels, which are "
      f"sparse/noisy on real Bandcamp tags.")
    p("- **Decision: MMR (lambda≈0.5) for production.** It honors the user's "
      "stated priority order — vibe-similar first (tightest dispersion, most "
      "anchored), then maximally diverse within that — exposes a single knob "
      "(lambda) spanning baseline→pure-spread, degrades gracefully when genre "
      "tags are missing (unlike stratified), and sits within a hair of the "
      "oracle. maxmin is the drop-in alternative when raw spread matters more "
      "than staying close to the seed (set lambda lower instead).")
    p("")

    print("\n".join(out))


if __name__ == "__main__":
    main()
